#!/usr/bin/env bash
# Deploy Live Translate (API + web app) to a VM from your Mac. Safe to re-run for every update.
#
# Usage:   ./deploy/deploy.sh <user@vm-ip> <path-to-ssh-private-key>
# Example: ./deploy/deploy.sh ubuntu@203.0.113.10 ~/.ssh/oracle-live-translate.key
#
# What it does:
#   1. First run only: creates deploy/.env (domains) and server/.env.production (secrets). Both are gitignored.
#      Without your own domain it uses free sslip.io names: api.<ip>.sslip.io and app.<ip>.sslip.io.
#   2. Builds the web app pointed at the production API.
#   3. Uploads server code, deploy config and the web build to /opt/live-translate on the VM.
#   4. Builds and (re)starts the containers. Caddy gets HTTPS certificates automatically.
set -euo pipefail

if [ $# -ne 2 ]; then
  sed -n '4,5p' "$0"
  exit 1
fi

TARGET="$1"
KEY="$2"
REMOTE_DIR=/opt/live-translate
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SSH_OPTS=(-i "$KEY" -o StrictHostKeyChecking=accept-new)
VM_IP="${TARGET#*@}"

[ -f "$KEY" ] || { echo "SSH key not found: $KEY"; exit 1; }
chmod 600 "$KEY"

# ---- 1. Config files (first run only) ----
if [ ! -f "$ROOT/deploy/.env" ]; then
  DASHED_IP="$(echo "$VM_IP" | tr '.' '-')"
  printf 'API_DOMAIN=api.%s.sslip.io\nAPP_DOMAIN=app.%s.sslip.io\n' "$DASHED_IP" "$DASHED_IP" > "$ROOT/deploy/.env"
  echo "==> Created deploy/.env with sslip.io domains (edit it later to use your own domain)."
fi
# shellcheck disable=SC1091
. "$ROOT/deploy/.env"
: "${API_DOMAIN:?API_DOMAIN missing in deploy/.env}"
: "${APP_DOMAIN:?APP_DOMAIN missing in deploy/.env}"

PROD_ENV="$ROOT/server/.env.production"
if [ ! -f "$PROD_ENV" ]; then
  [ -f "$ROOT/server/.env" ] || { echo "server/.env not found (copy server/.env.example first)"; exit 1; }
  # Reuse your local API keys/SMTP settings, but with a fresh JWT secret and locked-down CORS.
  JWT="$(openssl rand -hex 32)"
  grep -vE '^(JWT_SECRET|CORS_ORIGINS|DATABASE_PATH|NODE_ENV)=' "$ROOT/server/.env" > "$PROD_ENV"
  printf '\n# ---- Production overrides (generated by deploy.sh) ----\nJWT_SECRET=%s\nCORS_ORIGINS=https://%s\n' "$JWT" "$APP_DOMAIN" >> "$PROD_ENV"
  chmod 600 "$PROD_ENV"
  echo "==> Created server/.env.production (fresh JWT_SECRET, CORS limited to https://$APP_DOMAIN)."
fi

echo "==> API: https://$API_DOMAIN   Web: https://$APP_DOMAIN"

# ---- 2. Build the web app ----
echo "==> Building web app"
(
  cd "$ROOT/mobile"
  EXPO_PUBLIC_API_URL="https://$API_DOMAIN" EXPO_PUBLIC_WEB_URL="https://$APP_DOMAIN" \
    npx expo export --platform web --clear
)

# ---- 3. Prepare the VM (first run only) and upload ----
if ! ssh "${SSH_OPTS[@]}" "$TARGET" 'command -v docker >/dev/null && [ -d /opt/live-translate ]'; then
  echo "==> First deploy: setting up the VM (Docker, firewall)"
  scp "${SSH_OPTS[@]}" "$ROOT/deploy/setup-vm.sh" "$TARGET:/tmp/setup-vm.sh"
  ssh "${SSH_OPTS[@]}" "$TARGET" 'bash /tmp/setup-vm.sh'
fi

echo "==> Uploading files"
ssh "${SSH_OPTS[@]}" "$TARGET" "mkdir -p $REMOTE_DIR/server $REMOTE_DIR/deploy $REMOTE_DIR/mobile/dist"
RSYNC_SSH="ssh -i $KEY -o StrictHostKeyChecking=accept-new"
rsync -az --delete -e "$RSYNC_SSH" \
  --exclude node_modules --exclude dist --exclude data --exclude '.env*' --exclude .DS_Store \
  "$ROOT/server/" "$TARGET:$REMOTE_DIR/server/"
rsync -az -e "$RSYNC_SSH" --exclude .DS_Store "$ROOT/deploy/" "$TARGET:$REMOTE_DIR/deploy/"
rsync -az --delete -e "$RSYNC_SSH" "$ROOT/mobile/dist/" "$TARGET:$REMOTE_DIR/mobile/dist/"
scp -q "${SSH_OPTS[@]}" "$PROD_ENV" "$TARGET:$REMOTE_DIR/server/.env"
ssh "${SSH_OPTS[@]}" "$TARGET" "chmod 600 $REMOTE_DIR/server/.env"

# ---- 4. Start ----
echo "==> Building and starting containers on the VM"
ssh "${SSH_OPTS[@]}" "$TARGET" "cd $REMOTE_DIR/deploy && docker compose up -d --build --remove-orphans && docker compose ps"

echo
echo "Done. Give Caddy ~30 s to get HTTPS certificates, then check:"
echo "  API health: https://$API_DOMAIN/health"
echo "  Web app:    https://$APP_DOMAIN"
